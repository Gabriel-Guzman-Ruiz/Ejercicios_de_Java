package ejercicio1;

public class Ejercicio1 { 

	public static void main(String[] args) {
		
		int numero = 0;
		
		System.out.println("------------------------------");
		System.out.println("TODOS LOS NUMEROS DEL 1 AL 100");
		System.out.println("------------------------------");
		
		while (numero < 100) {
			
			numero ++;
			
			System.out.print(numero + " ");
			
		}
		
	}
		
}
	
