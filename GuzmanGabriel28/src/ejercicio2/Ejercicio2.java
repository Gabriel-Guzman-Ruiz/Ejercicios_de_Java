package ejercicio2;

public class Ejercicio2 { 

	public static void main(String[] args) {
		
		int numero = 0;
		
		System.out.println("------------------------------");
		System.out.println("TODOS LOS NUMEROS DEL 1 AL 100");
		System.out.println("------------------------------");
		
		do {
		
			numero ++;
			
			System.out.print(numero + " ");
		
		} while (numero < 100);
			
			
	}
		
}
	
